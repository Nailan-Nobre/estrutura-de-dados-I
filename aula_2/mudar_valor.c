#include <stdio.h>

int main() {
    int x = 10;
    int y = 5;
    printf("Valor inicial de x: %d\n", x);
    printf("Valor inicial de y: %d\n", y);

    // Alterando o valor de x
    x = 20;
    // Alterando o valor de y
    y = 10;
    printf("Novo valor de x: %d\n", x);
    printf("Novo valor de y: %d\n", y);

    return 0;
}